#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Automatic API & CLI Reference Generator for BACH (#2556)."""

from __future__ import annotations

import argparse
import ast
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
SYSTEM_DIR = REPO_ROOT / "system"
HUB_DIR = SYSTEM_DIR / "hub"
GUI_SERVER = SYSTEM_DIR / "gui" / "server.py"
DOCS_API_DIR = REPO_ROOT / "docs" / "api"
HELP_CLI_TXT = SYSTEM_DIR / "docs" / "help" / "cli.txt"

GENERATED_BANNER = "<!-- GENERATED BY system/tools/generate_api_cli_reference.py -- DO NOT EDIT MANUALLY -->"


def _extract_cli_handlers() -> list[dict[str, Any]]:
    handlers: list[dict[str, Any]] = []
    for py_file in sorted(HUB_DIR.glob("*.py")):
        if py_file.name.startswith("_"):
            continue
        try:
            tree = ast.parse(py_file.read_text(encoding="utf-8", errors="replace"))
        except SyntaxError:
            continue
        for node in tree.body:
            if not isinstance(node, ast.ClassDef):
                continue
            profile_name = None
            ops: list[str] = []
            for item in node.body:
                if isinstance(item, ast.FunctionDef) and item.name == "profile_name":
                    for stmt in ast.walk(item):
                        if isinstance(stmt, ast.Return) and isinstance(stmt.value, ast.Constant) and isinstance(stmt.value.value, str):
                            profile_name = stmt.value.value
                elif isinstance(item, ast.Assign):
                    for target in item.targets:
                        if isinstance(target, ast.Name) and target.id == "profile_name" and isinstance(item.value, ast.Constant) and isinstance(item.value.value, str):
                            profile_name = item.value.value
                elif isinstance(item, ast.FunctionDef) and item.name == "get_operations":
                    for stmt in ast.walk(item):
                        if isinstance(stmt, ast.Dict):
                            for k in stmt.keys:
                                if isinstance(k, ast.Constant) and isinstance(k.value, str):
                                    if k.value not in ops:
                                        ops.append(k.value)
            if profile_name:
                handlers.append({
                    "profile_name": profile_name,
                    "class_name": node.name,
                    "source": f"system/hub/{py_file.name}",
                    "operations": ops,
                })
    handlers.sort(key=lambda h: (h["profile_name"], h["class_name"]))
    return handlers


def _extract_http_routes() -> list[dict[str, Any]]:
    routes: list[dict[str, Any]] = []
    if not GUI_SERVER.exists():
        return routes
    tree = ast.parse(GUI_SERVER.read_text(encoding="utf-8", errors="replace"))
    http_methods = {"get", "post", "put", "delete", "patch"}
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            for dec in node.decorator_list:
                if isinstance(dec, ast.Call) and isinstance(dec.func, ast.Attribute):
                    if isinstance(dec.func.value, ast.Name) and dec.func.value.id == "app" and dec.func.attr in http_methods:
                        if dec.args and isinstance(dec.args[0], ast.Constant) and isinstance(dec.args[0].value, str):
                            routes.append({
                                "method": dec.func.attr.upper(),
                                "path": dec.args[0].value,
                                "handler": node.name,
                                "line": node.lineno,
                            })
    routes.sort(key=lambda r: (r["path"], r["method"], r["line"]))
    return routes


def _extract_canonical_modules() -> list[str]:
    bridge_file = HUB_DIR / "_services" / "ocean_stack_bridge.py"
    if not bridge_file.exists():
        return []
    tree = ast.parse(bridge_file.read_text(encoding="utf-8", errors="replace"))
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id == "CANONICAL_MODULES" and isinstance(node.value, (ast.Tuple, ast.List)):
                    return [elt.value for elt in node.value.elts if isinstance(elt, ast.Constant) and isinstance(elt.value, str)]
        elif isinstance(node, ast.AnnAssign):
            if isinstance(node.target, ast.Name) and node.target.id == "CANONICAL_MODULES" and isinstance(node.value, (ast.Tuple, ast.List)):
                return [elt.value for elt in node.value.elts if isinstance(elt, ast.Constant) and isinstance(elt.value, str)]
    return []


def build_artifacts() -> dict[Path, str]:
    handlers = _extract_cli_handlers()
    routes = _extract_http_routes()
    modules = _extract_canonical_modules()

    manifest = {
        "schema_version": "1.0.0",
        "generator": "system/tools/generate_api_cli_reference.py",
        "cli_handler_count": len(handlers),
        "http_route_count": len(routes),
        "canonical_module_count": len(modules),
        "canonical_modules": modules,
        "cli_handlers": handlers,
        "http_routes": routes,
    }

    api_lines = [
        GENERATED_BANNER,
        "# BACH HTTP API & Ocean Stack Reference",
        "",
        f"- **HTTP Routes (`system/gui/server.py`):** {len(routes)}",
        f"- **CLI Handlers (`system/hub/*.py`):** {len(handlers)}",
        f"- **Canonical Ocean Modules (`ocean_stack_bridge.py`):** {len(modules)}",
        "",
        "## Canonical Ocean Stack Bindings",
        "",
        "| # | Module |",
        "|---|---|",
    ]
    for idx, mod in enumerate(modules, 1):
        api_lines.append(f"| {idx} | `{mod}` |")
    api_lines.extend([
        "",
        "## HTTP Endpoints",
        "",
        "| Method | Path | Handler | Line |",
        "|---|---|---|---|",
    ])
    for r in routes:
        api_lines.append(f"| `{r['method']}` | `{r['path']}` | `{r['handler']}` | {r['line']} |")

    cli_lines = [
        GENERATED_BANNER,
        "# BACH CLI Handler Reference",
        "",
        f"Automatisch extrahiert aus `system/hub/*.py` ({len(handlers)} Handler).",
        "",
        "| Profile (`bach <profile>`) | Class | Source | Operations |",
        "|---|---|---|---|",
    ]
    for h in handlers:
        ops_str = ", ".join(f"`{op}`" for op in h["operations"]) if h["operations"] else "*(dynamic)*"
        cli_lines.append(f"| `{h['profile_name']}` | `{h['class_name']}` | `{h['source']}` | {ops_str} |")

    return {
        DOCS_API_DIR / "README.md": "\n".join(api_lines) + "\n",
        DOCS_API_DIR / "cli-reference.md": "\n".join(cli_lines) + "\n",
        DOCS_API_DIR / "reference-manifest.json": json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate or check BACH API & CLI reference docs (#2556).")
    parser.add_argument("--check", action="store_true", help="Check whether generated files match disk without writing.")
    args = parser.parse_args(argv)

    artifacts = build_artifacts()
    if args.check:
        drifted = []
        for path, expected in artifacts.items():
            if not path.exists():
                drifted.append(f"MISSING: {path.relative_to(REPO_ROOT)}")
                continue
            actual = path.read_text(encoding="utf-8")
            if actual != expected:
                drifted.append(f"DRIFT: {path.relative_to(REPO_ROOT)}")
        if drifted:
            for item in drifted:
                print(item, file=sys.stderr)
            return 1
        print("OK: API/CLI reference artifacts are up to date.")
        return 0

    DOCS_API_DIR.mkdir(parents=True, exist_ok=True)
    for path, content in artifacts.items():
        path.write_text(content, encoding="utf-8")
        print(f"WROTE {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
