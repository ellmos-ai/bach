def _get_agent_studio_ro_conn() -> sqlite3.Connection:
    conn = None
    try:
        conn = sqlite3.connect(BACH_DB.resolve().as_uri() + "?mode=ro", uri=True, timeout=2)
        conn.execute("PRAGMA query_only = ON")
        conn.row_factory = sqlite3.Row
        return conn
    except (OSError, sqlite3.Error):
        if conn is not None:
            conn.close()
        raise HTTPException(status_code=503, detail="Agenten-Daten nicht verfügbar")


def _read_schema_ready(conn: sqlite3.Connection, tables: tuple[str, ...]) -> None:
    """Inspect known table names and columns without bootstrap or seed writes."""
    try:
        for table in tables:
            required = _AGENT_STUDIO_READ_COLUMNS[table]
            if conn.execute("SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = ?",
                            (table,)).fetchone() is None:
                raise ValueError("missing_table")
            columns = {row[1] for row in conn.execute(f'PRAGMA table_info("{table}")')}
            if not required.issubset(columns):
                raise ValueError("missing_columns")
    except (sqlite3.Error, KeyError, ValueError):
        raise HTTPException(status_code=503, detail="Agenten-Daten noch nicht initialisiert")

def _ensure_agent_studio_tables(conn: sqlite3.Connection):
    global _agent_studio_tables_ready
    if _agent_studio_tables_ready:
        return
    try:
        ensure_blueprint_schema(conn)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS partner_presence (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                partner_name TEXT NOT NULL UNIQUE,
                status TEXT DEFAULT 'offline',
                clocked_in TEXT,
                last_heartbeat TEXT,
                current_task TEXT,
                session_id TEXT,
                created_at TEXT DEFAULT CURRENT_TIMESTAMP,
                updated_at TEXT DEFAULT CURRENT_TIMESTAMP
            )
        """)
        conn.commit()
        seed_default_blueprints(conn)
        _agent_studio_tables_ready = True
    except Exception as exc:
        logger.warning(f"Fehler bei Initialisierung der Agent-Studio Tabellen: {exc}")
        return


@router.get("/agent-studio/blueprints")
async def list_agent_blueprints(
    kind: Optional[str] = None,
    search: Optional[str] = None,
    is_template: Optional[int] = None,
):
    """Listet alle Schablonen und individuellen Agenten-Blueprints aus der Fabrika."""
    conn = _get_agent_studio_ro_conn()
    try:
        _read_schema_ready(conn, ("agent_blueprints",))
        rows = conn.execute("""
            SELECT * FROM agent_blueprints
            ORDER BY is_template DESC, name ASC
        """).fetchall()
        blueprints = []
        templates = []
        for r in rows:
            item = dict(r)
            item["kind"] = item.get("kind") or "agent"
            item["version"] = item.get("version") or "1.0.0"
            item["start_prompt"] = item.get("start_prompt") or ""
            try:
                item["skills"] = json.loads(item.get("skills_json") or "[]")
            except Exception:
                item["skills"] = []
            item["skills_validation"] = svc_validate_blueprint_skills(item["skills"])
            try:
                item["contractus"] = json.loads(item.get("contractus_json") or "{}")
            except Exception:
                item["contractus"] = {}
            try:
                item["governance"] = json.loads(item.get("governance_json") or "{}")
            except Exception:
                item["governance"] = {}

            # Filter by kind
            if isinstance(kind, str) and kind.strip() and item["kind"].lower() != kind.strip().lower():
                continue
            # Filter by is_template
            if is_template is not None and not isinstance(is_template, type(Query)):
                try:
                    if int(item.get("is_template", 0)) != int(is_template):
                        continue
                except (ValueError, TypeError):
                    pass
            # Filter by search
            if isinstance(search, str) and search.strip():
                term = search.strip().lower()
                target_str = f"{item.get('name', '')} {item.get('title', '')} {item.get('description', '')} {item.get('persona_role', '')}".lower()
                if term not in target_str:
                    continue

            if item["is_template"]:
                templates.append(item)
            else:
                blueprints.append(item)
        from .core_system_agents import _snapshot as core_snapshot
        try:
            slots = await asyncio.to_thread(core_snapshot)
        except HTTPException:
            slots = {"agents": [], "configuration_version": None}
        by_blueprint = {slot["blueprint_id"]: slot for slot in slots["agents"]
                        if type(slot.get("blueprint_id")) is int}
        for item in templates + blueprints:
            item["instance"] = by_blueprint.get(item["id"])
        return {
            "templates": templates,
            "blueprints": blueprints,
            "total_templates": len(templates),
            "total_blueprints": len(blueprints),
            "total": len(templates) + len(blueprints),
            "configuration_version": slots["configuration_version"],
        }
    finally:
        conn.close()


