def _lock_cache_snapshot() -> Dict[str, Any]:
    """Read the generated lock-scan feed without scanning the filesystem."""
    configured = os.environ.get("BACH_LOCK_CACHE")
    candidates = ([Path(os.path.expanduser(configured))] if configured else
                  [Path(os.path.expanduser("~/OneDrive/_scripts/LOCK-CACHE.md"))])
    cache = _find_existing_path(candidates)
    checked_at = datetime.now(timezone.utc).isoformat()
    unavailable = {
        "availability": "unavailable", "source": "lock_scan_cache",
        "checked_at": checked_at, "scanned_at": None, "count": None,
        "locks": [], "error": "lock_cache_missing",
    }
    if cache is None:
        return unavailable
    try:
        lines = cache.read_text(encoding="utf-8").splitlines()
        if not lines or "AUTO-GENERATED by lock_scan.py" not in lines[0]:
            raise ValueError("invalid_header")
        stamp = next(line.partition(": ")[2] for line in lines if line.startswith("As of: "))
        count = int(next(line.partition(": ")[2] for line in lines if line.startswith("Active locks: ")))
        scanned = datetime.fromisoformat(stamp)
        if scanned.tzinfo is None:
            scanned = scanned.astimezone()
        locks = []
        for line in lines:
            if not line.startswith("| ") or line.startswith("| Path ") or line.startswith("|---") or "_(no active locks)_" in line:
                continue
            cells = [cell.strip() for cell in line.strip("|").split("|")]
            if len(cells) != 5:
                raise ValueError("invalid_row")
            # The path and owner may contain private local details. Only expose
            # the lock filename and its scope; the source feed stays authoritative.
            name = Path(cells[0].replace("\\", "/").removesuffix(" (legacy)")).name
            locks.append({"name": name, "scope": cells[1], "type": "lock", "status": "active"})
        if count != len(locks):
            raise ValueError("count_mismatch")
        age = (datetime.now(timezone.utc) - scanned.astimezone(timezone.utc)).total_seconds()
        if age < -60 or age > 1800:
            return {**unavailable, "availability": "stale", "scanned_at": scanned.isoformat(),
                    "error": "lock_cache_stale"}
        return {"availability": "available", "source": "lock_scan_cache",
                "checked_at": checked_at, "scanned_at": scanned.isoformat(),
                "count": count, "locks": locks, "error": None}
    except (OSError, ValueError, StopIteration, UnicodeError):
        return {**unavailable, "error": "lock_cache_invalid"}


def _require_memory_device(request: Request) -> int:
    """Authorize private search with an active device token using a RO query."""
    header = request.headers.get("Authorization", "")
    token = header[7:].strip() if header.startswith("Bearer ") else request.cookies.get("bach_device_token", "").strip()
    if not token:
        raise HTTPException(status_code=401, detail="Device token required")
    token_hash = hashlib.sha256(token.strip().encode("utf-8")).hexdigest()
    try:
        with closing(sqlite3.connect(BACH_DB.resolve().as_uri() + "?mode=ro", uri=True, timeout=2)) as conn:
            conn.execute("PRAGMA query_only = ON")
            row = conn.execute(
                "SELECT id FROM devices WHERE token_hash = ? AND status = 'active'",
                (token_hash,),
            ).fetchone()
    except (OSError, sqlite3.Error):
        raise HTTPException(status_code=503, detail="Device authorization unavailable")
    if row is None:
        raise HTTPException(status_code=403, detail="Device token invalid or revoked")
    return int(row[0])


