def _ensure_calendar_tables(conn: sqlite3.Connection):
    conn.execute("""
        CREATE TABLE IF NOT EXISTS assistant_calendar (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            title TEXT NOT NULL,
            event_type TEXT DEFAULT 'termin',
            start_datetime TEXT NOT NULL,
            end_datetime TEXT,
            location TEXT,
            description TEXT,
            attendees TEXT,
            status TEXT DEFAULT 'geplant',
            reminder_minutes INTEGER DEFAULT 15,
            is_recurring INTEGER DEFAULT 0,
            recurrence_rule TEXT,
            external_id TEXT,
            created_at TEXT,
            updated_at TEXT,
            dist_type TEXT,
            event_origin TEXT NOT NULL DEFAULT 'unknown'
        )
    """)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS household_routines (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            name TEXT NOT NULL,
            frequency TEXT DEFAULT 'taeglich',
            category TEXT DEFAULT 'Haushalt',
            next_due TEXT,
            is_active INTEGER DEFAULT 1
        )
    """)
    conn.commit()


@router.get("/calendar/events")
async def get_calendar_events(
    view: str = Query("month", description="day|week|month|year|list"),
    date: Optional[str] = Query(None, description="ISO-Datum YYYY-MM-DD"),
    include_routines: bool = Query(True, description="Fällige Haushalts-/Lebensroutinen einblenden")
):
    """Liefert Termine aus assistant_calendar und optionale fällige Routinen."""
    conn = _get_conn()
    conn.row_factory = sqlite3.Row
    try:
        # Legacy databases may lack event_origin. Reading never migrates them.
        # Distribution type is not evidence of a user's or system's authorship.
        query = "SELECT * FROM assistant_calendar WHERE 1=1"
        params = []

        if date:
            if view == "day":
                query += " AND start_datetime BETWEEN ? AND ?"
                params.extend([f"{date} 00:00:00", f"{date} 23:59:59"])
            elif view == "week":
                try:
                    selected = datetime.strptime(date, "%Y-%m-%d")
                except ValueError as exc:
                    raise HTTPException(status_code=422, detail="Ungültiges Kalenderdatum") from exc
                monday = selected - timedelta(days=selected.weekday())
                next_monday = monday + timedelta(days=7)
                query += " AND start_datetime >= ? AND start_datetime < ?"
                params.extend([monday.strftime("%Y-%m-%d 00:00:00"), next_monday.strftime("%Y-%m-%d 00:00:00")])
            elif view == "month" and len(date) >= 7:
                month_prefix = date[:7]
                query += " AND start_datetime LIKE ?"
                params.append(f"{month_prefix}%")
            elif view == "year" and len(date) >= 4:
                year_prefix = date[:4]
                query += " AND start_datetime LIKE ?"
                params.append(f"{year_prefix}%")

        query += " ORDER BY start_datetime ASC"
        try:
            rows = conn.execute(query, params).fetchall()
        except sqlite3.OperationalError as exc:
            if "no such table: assistant_calendar" not in str(exc):
                raise
            rows = []
        events = []
        for row in rows:
            event = dict(row)
            event["origin"] = event.get("event_origin") if event.get("event_origin") in {"user", "system"} else "unknown"
            events.append(event)

        if include_routines:
            try:
                r_rows = conn.execute("SELECT id, name, frequency, category, next_due FROM household_routines WHERE is_active = 1 AND next_due IS NOT NULL AND TRIM(next_due) != ''").fetchall()
                for r in r_rows:
                    events.append({
                        "id": f"routine_{r['id']}",
                        "title": r["name"],
                        "event_type": "routine",
                        "start_datetime": r["next_due"],
                        "end_datetime": None,
                        "location": r["category"],
                        "description": f"Lebensroutine: {r['frequency']} ({r['category']})",
                        "status": "aktiv",
                        "is_recurring": 1,
                        "recurrence_rule": r["frequency"],
                        "is_routine": True,
                        "origin": "unknown",
                    })
            except Exception:
                pass

        return {"events": events, "count": len(events), "view": view, "date": date}
    finally:
        conn.close()


@router.post("/calendar/events")
async def create_calendar_event(payload: Dict[str, Any] = Body(...)):
    """Erstellt einen neuen Kalender-Termin in assistant_calendar."""
    title = payload.get("title", "").strip()
    if not title:
        raise HTTPException(status_code=400, detail="Titel erforderlich")
    start_dt = payload.get("start_datetime") or payload.get("start")
    if not start_dt:
        start_dt = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    end_dt = payload.get("end_datetime") or payload.get("end")
    event_type = payload.get("event_type", "termin")
    location = payload.get("location", "")
    description = payload.get("description", "")
    status = payload.get("status", "geplant")
    reminder = payload.get("reminder_minutes", 15)
    is_recurring = 1 if payload.get("is_recurring") else 0
    recurrence_rule = payload.get("recurrence_rule")

    conn = _get_conn()
    try:
        existing = conn.execute("SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = 'assistant_calendar'").fetchone()
        if existing and "event_origin" not in {row[1] for row in conn.execute("PRAGMA table_info(assistant_calendar)")}:
            raise HTTPException(status_code=503, detail="Kalenderschema benötigt die additive Herkunftsmigration")
        _ensure_calendar_tables(conn)
        cursor = conn.cursor()
        now = datetime.now().isoformat()
        cursor.execute("""
            INSERT INTO assistant_calendar (
                title, event_type, start_datetime, end_datetime, location,
                description, status, reminder_minutes, is_recurring,
                recurrence_rule, created_at, updated_at, event_origin
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (title, event_type, start_dt, end_dt, location, description, status, reminder, is_recurring, recurrence_rule, now, now, "user"))
        new_id = cursor.lastrowid
        conn.commit()
        return {"ok": True, "id": new_id, "title": title}
    finally:
        conn.close()


